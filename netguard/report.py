"""Self-contained HTML security report (no external assets)."""

import html
import time

SEV_COLOR = {"CRITICAL": "#b42318", "HIGH": "#c4540a", "MEDIUM": "#9a6700", "LOW": "#1a7f37"}

CSS = """
:root{--bg:#fff;--fg:#1f2328;--mut:#656d76;--line:#d0d7de;--card:#f6f8fa}
@media(prefers-color-scheme:dark){:root{--bg:#0d1117;--fg:#e6edf3;--mut:#8b949e;--line:#30363d;--card:#161b22}}
body{font:15px/1.5 system-ui,sans-serif;background:var(--bg);color:var(--fg);max-width:960px;margin:0 auto;padding:24px 16px}
h1{margin:0 0 4px}h2{margin-top:32px;border-bottom:1px solid var(--line);padding-bottom:6px}
.mut{color:var(--mut)}table{border-collapse:collapse;width:100%;margin:12px 0}
th,td{text-align:left;padding:8px 10px;border-bottom:1px solid var(--line);vertical-align:top}
th{background:var(--card);font-weight:600}
.kpis{display:grid;grid-template-columns:repeat(auto-fit,minmax(130px,1fr));gap:10px}
.kpi{background:var(--card);border:1px solid var(--line);border-radius:8px;padding:12px}
.kpi b{display:block;font-size:22px}.badge{color:#fff;border-radius:4px;padding:1px 8px;font-size:12px;font-weight:600}
code{background:var(--card);padding:1px 5px;border-radius:4px}
"""


def _e(value):
    return html.escape(str(value))


def build(path, alerts=None, stats=None, scan=None, title="NetGuard Security Report"):
    out = [f"<!doctype html><html lang=en><meta charset=utf-8>"
           f"<meta name=viewport content='width=device-width,initial-scale=1'>"
           f"<title>{_e(title)}</title><style>{CSS}</style><body>",
           f"<h1>{_e(title)}</h1><div class=mut>Generated {time.strftime('%Y-%m-%d %H:%M')}</div>"]

    if stats:
        crit = sum(1 for a in alerts or [] if a.severity in ("CRITICAL", "HIGH"))
        out.append("<h2>Traffic summary</h2><div class=kpis>")
        for label, val in [("Packets", f"{stats['packets']:,}"), ("Hosts", stats["hosts"]),
                           ("Duration", f"{stats['duration']}s"), ("Alerts", len(alerts or [])),
                           ("High / Critical", crit)]:
            out.append(f"<div class=kpi><span class=mut>{label}</span><b>{_e(val)}</b></div>")
        out.append("</div><table><tr><th>Protocol</th><th>Packets</th><th>Top talkers</th><th>Packets</th></tr>")
        protos = stats["protocols"].most_common()
        talkers = stats["talkers"].most_common(len(protos) or 1)
        for i in range(max(len(protos), min(5, len(talkers)))):
            pr = protos[i] if i < len(protos) else ("", "")
            tk = talkers[i] if i < len(talkers) and i < 5 else ("", "")
            out.append(f"<tr><td>{_e(pr[0])}</td><td>{_e(pr[1])}</td><td>{_e(tk[0])}</td><td>{_e(tk[1])}</td></tr>")
        out.append("</table>")

    if alerts is not None:
        out.append(f"<h2>Detections ({len(alerts)})</h2>")
        if alerts:
            out.append("<table><tr><th>Severity</th><th>Rule</th><th>Source</th><th>Target</th>"
                       "<th>Detail</th><th>MITRE</th></tr>")
            for a in alerts:
                out.append(f"<tr><td><span class=badge style='background:{SEV_COLOR[a.severity]}'>{a.severity}"
                           f"</span></td><td>{_e(a.rule)}</td><td><code>{_e(a.src)}</code></td>"
                           f"<td><code>{_e(a.dst)}</code></td><td>{_e(a.detail)}</td><td>{_e(a.mitre)}</td></tr>")
            out.append("</table>")
        else:
            out.append("<p>No suspicious activity detected.</p>")

    if scan:
        c = scan["counts"]
        out.append(f"<h2>Port scan: {_e(scan['target'])} ({_e(scan['ip'])})</h2>"
                   f"<p class=mut>{scan['scanned']} ports in {scan['elapsed_s']}s - "
                   f"{c['open']} open, {c['closed']} closed, {c['filtered']} filtered</p>")
        if scan["open_ports"]:
            out.append("<table><tr><th>Port</th><th>Service</th><th>Banner</th><th>Finding</th></tr>")
            for r in scan["open_ports"]:
                out.append(f"<tr><td>{r['port']}/tcp</td><td>{_e(r['service'])}</td>"
                           f"<td><code>{_e(r.get('banner', ''))}</code></td><td>{_e(r.get('risk', '-'))}</td></tr>")
            out.append("</table>")

    out.append("<p class=mut>Generated by NetGuard. Use only on networks you are authorised to monitor.</p></body></html>")
    with open(path, "w", encoding="utf-8") as fh:
        fh.write("".join(out))
    return path
